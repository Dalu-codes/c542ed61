"""Generate docs/data-audit.md from the committed snapshot.

    python -m app.audit            # from backend/

Every number in the report is computed here from the snapshot, using the same
service functions the API uses. Re-running it on the same snapshot gives the
same report.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from . import config
from .domain.evaluation import Alignment
from .domain.gates import GATE_PRESETS, UK, parse_gate
from .service import (
    actual_stats,
    after_the_fact,
    evaluate,
    gate_comparison,
    lead_profile,
    schedule_stats,
    shifted_gate,
)
from .store import get_snapshot

MINUS = "−"


def mw(x: float | None) -> str:
    return "—" if x is None else f"{x:,.0f}".replace("-", MINUS)


def signed(x: float | None) -> str:
    if x is None:
        return "—"
    return ("+" if x >= 0 else MINUS) + f"{abs(x):,.0f}"


def uk(ts) -> str:
    return ts.astimezone(UK).strftime("%a %d %b %H:%M")


def render() -> str:
    snap = get_snapshot()
    sched = schedule_stats(snap)
    acts = actual_stats(snap)
    fr, ar = snap.forecast_report, snap.actual_report
    base = evaluate(snap, parse_gate("0920"))
    m = base.metrics
    L: list[str] = []
    w = L.append

    w("# Data audit — January 2026 snapshot\n")
    w(f"Generated by `python -m app.audit` from snapshot `{snap.snapshot_id}`. "
      "All times UK local (GMT in January, so equal to UTC). Power in MW, averaged over the interval.\n")

    w("## Summary\n")
    w(f"- **Complete data.** {fr.accepted:,} of {fr.received:,} forecast values and {ar.accepted:,} of {ar.received:,} "
      "actual half-hours accepted; nothing rejected, duplicated or revised.")
    w(f"- **{sched.runs} forecast runs** over {sched.days} days, {', '.join(f'{k} per day on {v} days' for k, v in sorted(sched.runs_per_day.items()))}; "
      f"each run has {', '.join(str(k) for k in sched.points_per_run)} hourly points.")
    w(f"- **Every one of the {base.coverage.expected} delivery hours is scorable at every gate.**")
    w(f"- **At the 09:20 gate:** MAE {mw(m.mae_mw)} MW, RMSE {mw(m.rmse_mw)} MW, mean error {signed(m.mean_error_mw)} MW, "
      f"P90 |error| {mw(m.p90_abs_error_mw)} MW; the forecast was above the actual in {m.n_over} of {m.n} hours.")
    w(f"- **A constant over-forecast explains {m.bias_share:.0%} of the squared error** "
      f"(bias {signed(m.mean_error_mw)} MW, varying part {mw(m.spread_mw)} MW).")
    atf = after_the_fact(snap)
    w(f"- **The gap survives hindsight:** values runs give for hours that had already started when they were published "
      f"are still {signed(atf.mean_error_mw)} MW above the metered actual on average (n = {atf.n:,}). "
      "Part of the error is therefore a difference between what WINDFOR describes and what FUELHH meters. "
      "The cause (e.g. curtailment, coverage) cannot be determined from these two datasets.\n")

    w("## Sources and retrieval\n")
    wf, fh = snap.manifest.get("windfor", {}), snap.manifest.get("fuelhh", {})
    w(f"- WINDFOR stream, runs published {wf.get('publishFrom')} to {wf.get('publishTo')} (exclusive), one request per day.")
    w(f"- FUELHH stream, fuelType=WIND, settlement dates {fh.get('settlementDateFrom')} to {fh.get('settlementDateTo')}, one request per day.")
    w(f"- {len(snap.manifest.get('requests', []))} requests, all HTTP 200; details in `data/snapshot/manifest.json`.")
    w("- Definitions from Elexon's OpenAPI spec: FUELHH gives \"average MW values over 30 minutes\"; "
      "WINDFOR covers \"wind farms which are visible to the ESO and have operational metering\".\n")

    w("## Forecasts (WINDFOR)\n")
    w("| Check | Result |\n| --- | --- |")
    w(f"| Records received / accepted | {fr.received:,} / {fr.accepted:,} |")
    w(f"| Rejected by reason | {dict(fr.rejected) or 'none'} |")
    w(f"| Duplicates merged | {fr.collapsed_duplicates} |")
    w(f"| Runs | {sched.runs} ({uk(sched.first_run)} → {uk(sched.last_run)}) |")
    w(f"| Points per run | {dict(sched.points_per_run)} |")
    w(f"| Minute of `startTime` | {dict(sched.start_minutes)} → hourly resolution |")
    clock = ", ".join(f"{t} ({c})" for t, c in sorted(sched.publish_clock_times.items()))
    w(f"| Publish clock times (count) | {clock} |")
    w(f"| Off-schedule runs | {', '.join(uk(t) for t in sched.off_schedule_runs) or 'none'} |\n")
    w("**Documentation mismatch.** Elexon's description of the wind forecast endpoints says runs are published at "
      "03:30, 05:30, 08:30, 10:30, 12:30, 16:30, 19:30 and 23:30. The January `publishTime` values are one hour earlier. "
      "July 2026 data matches the documented times, so either the documentation or the winter timestamps are an hour off. "
      "ForeCheck uses `publishTime` as recorded (decision agreed 26 Oct 2026). Impact if runs were really available 60 minutes later:\n")
    w("| Gate | Run used (as recorded) | MAE | Run used (+60 min) | MAE |\n| --- | --- | --- | --- | --- |")
    for g in GATE_PRESETS:
        a, b = evaluate(snap, g), evaluate(snap, shifted_gate(g, 60))
        ra = sorted({r.astimezone(UK).strftime('%H:%M') for d in a.days for r in d.runs_used})
        rb = sorted({r.astimezone(UK).strftime('%H:%M') for d in b.days for r in d.runs_used})
        w(f"| {g.local_time:%H:%M} {g.label} | {', '.join(ra)} | {mw(a.metrics.mae_mw)} | {', '.join(rb)} | {mw(b.metrics.mae_mw)} |")
    w("")

    w("## Actuals (FUELHH, WIND)\n")
    w("| Check | Result |\n| --- | --- |")
    w(f"| Records received / accepted | {ar.received:,} / {ar.accepted:,} |")
    w(f"| Rejected by reason | {dict(ar.rejected) or 'none'} |")
    w(f"| Half-hours present / expected | {acts.half_hours:,} / {acts.expected_half_hours:,} |")
    w(f"| Revisions superseded | {ar.revisions_superseded} |")
    lags = ", ".join(f"{k} min ({v})" for k, v in sorted(acts.publish_lag_minutes.items()))
    w(f"| `publishTime` − `startTime` | {lags} |")
    late = "; ".join(f"{uk(s)} (+{lag} min)" for s, lag in acts.late_publications) or "none"
    w(f"| Published later than usual | {late} |\n")

    w("## Decision-time coverage by gate\n")
    w("| Gate | Run used (days) | Hours scored | No forecast | No actual | MAE | Mean error | RMSE | P90 |\n"
      "| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for r in gate_comparison(snap):
        c, gm = r.period.coverage, r.period.metrics
        used = ", ".join(f"{t} ({n})" for t, n in sorted(r.runs_used.items()))
        w(f"| {r.gate.local_time:%H:%M} {r.gate.label} | {used} | {c.scored}/{c.expected} | {c.no_forecast} | {c.no_actual} | "
          f"{mw(gm.mae_mw)} | {signed(gm.mean_error_mw)} | {mw(gm.rmse_mw)} | {mw(gm.p90_abs_error_mw)} |")
    ages = sorted({(d.cutoff - d.runs_used[0]).total_seconds() / 60 for d in base.days if d.runs_used})
    w(f"\nAt 09:20 the run used was {', '.join(f'{int(a // 60)}h {int(a % 60):02d}m' for a in ages)} old at the gate on every day.\n")

    w("## Alignment sensitivity (hourly forecast vs half-hourly actual)\n")
    w("| Alignment | MAE | Mean error | RMSE | Hours |\n| --- | --- | --- | --- | --- |")
    for al, name in [(Alignment.EXACT, "Exact start time (used)"), (Alignment.HOUR_MEAN, "Mean of both half-hours (check)")]:
        pm = evaluate(snap, parse_gate("0920"), al).metrics
        w(f"| {name} | {mw(pm.mae_mw)} | {signed(pm.mean_error_mw)} | {mw(pm.rmse_mw)} | {pm.n} |")
    w("")

    w("## Error by lead time (all runs, diagnostic)\n")
    w("Every run scored against actuals by hours between publication and delivery. Not a decision-time view.\n")
    w("| Lead (h) | Pairs | MAE | Mean error |\n| --- | --- | --- | --- |")
    for b in lead_profile(snap):
        w(f"| {b.lo_hours}–{b.hi_hours} | {b.metrics.n:,} | {mw(b.metrics.mae_mw)} | {signed(b.metrics.mean_error_mw)} |")
    w("")

    w("## Each decision at 09:20\n")
    w("| Decision | Delivery | Run used | Hours | MAE | Mean error | Mean actual |\n| --- | --- | --- | --- | --- | --- | --- |")
    for d in base.days:
        run = d.runs_used[0].astimezone(UK).strftime("%H:%M") if d.runs_used else "—"
        w(f"| {d.cutoff.astimezone(UK):%a %d %b} | {d.delivery_day:%a %d %b} | {run} | {d.coverage.scored}/{d.coverage.expected} | "
          f"{mw(d.metrics.mae_mw)} | {signed(d.metrics.mean_error_mw)} | {mw(d.metrics.mean_actual_mw)} |")
    w("\nDaily figures are for drill-down only; month figures are computed from all hours, not averaged from days.")
    return "\n".join(L) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description="Write the data audit report.")
    p.add_argument("--out", type=Path, default=config.REPO_ROOT / "docs" / "data-audit.md")
    a = p.parse_args()
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(render())
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
